CREATE TABLE pios_sessions (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(320)
);
CREATE UNIQUE INDEX pios_sessions_id_idx ON pios_sessions (SESSION_ID);
CREATE INDEX pios_sessions_expiry_idx ON pios_sessions (EXPIRY_TIME);
CREATE INDEX pios_sessions_principal_idx ON pios_sessions (PRINCIPAL_NAME);
CREATE TABLE pios_sessions_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES pios_sessions(PRIMARY_ID) ON DELETE CASCADE
);
